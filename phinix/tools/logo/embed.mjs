/**
 * Embeds the vectorised emblem into a typed module.
 * Runs before `next build` (and can be re-run after re-tracing the logo), so the
 * SVG markup is a plain string: no runtime fs, no extra network request, and it
 * works in both server and client components.
 */
import fs from 'node:fs'

const src = fs.readFileSync('public/phinix-emblem.svg', 'utf8')
const viewBox = (src.match(/viewBox="([^"]+)"/) || [])[1] || '0 0 64 64'
const inner = src
  .replace(/^[\s\S]*?<svg[^>]*>/, '')
  .replace(/<\/svg>\s*$/, '')
  .trim()

// gradient ids must be unique per document — they are already prefixed (phx-*)
const out = `/* AUTO-GENERATED by tools/logo/embed.mjs — do not edit by hand.
   Source: public/phinix-emblem.svg (vectorised from the uploaded logo). */

export const emblemViewBox = ${JSON.stringify(viewBox)}

export const emblemMarkup = ${JSON.stringify(inner)}
`
fs.writeFileSync('src/data/emblem.ts', out)
console.log(`src/data/emblem.ts — ${(out.length / 1024).toFixed(1)} KB, viewBox ${viewBox}`)
